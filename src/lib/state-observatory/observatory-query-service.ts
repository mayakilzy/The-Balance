// ============================================================
// state-observatory/observatory-query-service.ts
// ------------------------------------------------------------
// Read-only tenant-scoped query layer — Observatory Snapshot.
//
// Per Mission 02-02 spec (decisions B10, B11, B12, B13):
//   - Snapshot scoped to (tenant, strategyVersionId, observationPeriodId)
//   - 4 layers per indicator (B12):
//     (a) observedFacts — observation values, sources, dates
//     (b) calculatedComparisons — variance records
//     (c) uncertainties — unknowns, observability mode, independence
//     (d) interpretations — alerts
//   - NO causal claims (B13) — attributionLevel="descriptive" everywhere
//   - Per-indicator independence assessment (not single ambiguous aggregate)
//   - Counter-evidence retrieved via Evidence.relatedEvidenceId (B11 correction)
//   - Cross-period/strategy data does NOT leak (B10 correction)
// ============================================================
import { withAuthenticatedTenant } from "@/lib/security/tenant-context";
import { requirePermissionWithCurrentRole } from "@/lib/permissions";
import { writeAuditTx } from "@/lib/audit";
import type { Session } from "next-auth";
import { analyzeAggregateIndependence } from "./aggregate-independence-service";

export interface EvidenceSummary {
  id: string;
  claim: string;
  type: string; // "supporting" | "counter" | "neutral"
  verificationStatus: string;
  sourceId: string | null;
  observedAt: string | null;
  relation: "direct" | "related"; // how it links to the observation
}

export interface IndicatorSnapshot {
  indicator: {
    id: string;
    code: string;
    displayName: string;
    unit: string;
    preferredDirection: string;
  };
  // Layer 1: OBSERVED FACTS (B12)
  observedFacts: {
    currentObservation: {
      id: string;
      observedValue: number | null;
      observedAt: string | null;
      originType: string;
      verificationStatus: string;
      isSynthetic: boolean;
      geoLevel: string;
      geoRefId: string | null;
    } | null;
    observationHistoryCount: number;
    correctionChain: Array<{
      id: string;
      observedValue: number | null;
      correctionReason: string | null;
      correctedAt: string | null;
      isCurrent: boolean;
    }>;
  };
  // Layer 2: CALCULATED COMPARISONS (B12)
  calculatedComparisons: {
    varianceRecord: {
      id: string;
      plannedValue: number | null;
      plannedValueType: string;
      varianceAbsolute: number | null;
      varianceDirection: string;
      comparisonValid: boolean;
      attributionLevel: string; // always "descriptive" (B13)
    } | null;
  };
  // Layer 3: UNCERTAINTIES (B12)
  uncertainties: {
    unknowns: string[];
    observabilityMode: "FULL" | "PARTIAL" | "LOW";
    limitationReason: string | null;
    independenceAssessment: {
      totalSources: number;
      independentSourceCount: number;
      verifiedEvidenceCount: number;
      nationalClaimSupportLevel: "none" | "partial" | "strong";
      geographicCoverageNotEqualsIndependence: true;
    };
  };
  // Layer 4: INTERPRETATIONS (B12)
  interpretations: {
    alerts: Array<{
      id: string;
      title: string;
      severity: string;
      lifecycleStage: string;
      executionStatus: string;
      isAutoGenerated: boolean;
    }>;
  };
  // Linked evidence (preserved — including disputed/refuted per A13)
  // B11 correction: includes evidence linked via Observation.evidenceId (direct)
  // AND evidence linked via Evidence.relatedEvidenceId (related)
  linkedEvidence: {
    supporting: EvidenceSummary[];
    contradictory: EvidenceSummary[];
    disputed: EvidenceSummary[];
    refuted: EvidenceSummary[];
  };
  // Source provenance
  sourceProvenance: {
    sourceId: string | null;
    sourceCode: string | null;
    sourceDisplayName: string | null;
    independenceGroup: string | null;
    reviewStatus: string | null;
    submittedByTenantId: string | null;
    provenanceWarnings: string[];
  };
}

export interface ObservatorySnapshot {
  strategyVersion: {
    id: string;
    status: string;
    versionNumber: number;
  };
  observationPeriod: {
    id: string;
    periodType: string;
    periodValue: string;
  };
  indicators: IndicatorSnapshot[];
  // Per-indicator aggregate independence assessments (keyed by indicatorId)
  // B10 correction: NOT a single ambiguous aggregate — explicitly keyed collection
  aggregateIndependenceByIndicator: Array<{
    indicatorId: string;
    indicatorCode: string;
    analysis: unknown; // AggregateIndependenceAnalysis shape (typed loosely to avoid circular import)
  }>;
  generatedAt: string;
  honesty: {
    simulatedData: boolean;
    limitations: string[];
    noCausalClaims: true; // B13
  };
}

export async function getObservatorySnapshot(
  session: Session | null,
  params: { strategyVersionId: string; observationPeriodId: string }
): Promise<ObservatorySnapshot> {
  // B10: authorize all 3 read permissions
  await requirePermissionWithCurrentRole(session, "observatory:observation:read");
  await requirePermissionWithCurrentRole(session, "observatory:variance:read");
  await requirePermissionWithCurrentRole(session, "observatory:alert:read");

  return withAuthenticatedTenant(session, async ({ tx, tenantId, userId }) => {
    // B10: verify strategyVersionId is approved in this tenant
    const sv = await tx.strategyVersion.findFirst({
      where: { id: params.strategyVersionId, tenantId, status: "approved" },
      select: { id: true, status: true, versionNumber: true },
    });
    if (!sv) {
      throw new Error(
        `StrategyVersion ${params.strategyVersionId} not found or not approved in tenant`
      );
    }

    // B10: verify observationPeriodId belongs to this tenant
    const period = await tx.observationPeriod.findFirst({
      where: { id: params.observationPeriodId, tenantId },
      select: { id: true, periodType: true, periodValue: true },
    });
    if (!period) {
      throw new Error(
        `ObservationPeriod ${params.observationPeriodId} not found in tenant`
      );
    }

    // Fetch all indicators linked to this strategy version
    const indicators = await tx.indicatorDefinition.findMany({
      where: { tenantId, strategyVersionId: params.strategyVersionId },
      select: {
        id: true,
        code: true,
        displayName: true,
        unit: true,
        preferredDirection: true,
      },
    });

    const indicatorSnapshots: IndicatorSnapshot[] = [];
    const aggregateIndependenceByIndicator: Array<{
      indicatorId: string;
      indicatorCode: string;
      analysis: unknown;
    }> = [];

    let anySimulated = false;
    const allLimitations = new Set<string>();

    for (const indicator of indicators) {
      // Layer 1: observedFacts
      // Current observation (national geo only — per 02-00 design)
      const currentObs = await tx.observation.findFirst({
        where: {
          tenantId,
          indicatorDefinitionId: indicator.id,
          observationPeriodId: params.observationPeriodId,
          geoLevel: "national",
          isCurrent: true,
        },
        select: {
          id: true,
          observedValue: true,
          observedAt: true,
          originType: true,
          verificationStatus: true,
          isSynthetic: true,
          geoLevel: true,
          geoRefId: true,
          evidenceId: true,
          sourceId: true,
        },
      });

      if (currentObs?.isSynthetic) anySimulated = true;

      // Correction history (ALL observations for this indicator+period, including superseded)
      const allObsHistory = await tx.observation.findMany({
        where: {
          tenantId,
          indicatorDefinitionId: indicator.id,
          observationPeriodId: params.observationPeriodId,
        },
        select: {
          id: true,
          observedValue: true,
          correctionReason: true,
          correctedAt: true,
          isCurrent: true,
          createdAt: true,
        },
        orderBy: { createdAt: "asc" },
      });

      // Layer 2: calculatedComparisons
      // B10 correction: only variance records for THIS indicator + period
      const varianceRecord = await tx.varianceRecord.findFirst({
        where: {
          tenantId,
          indicatorDefinitionId: indicator.id,
          observationPeriodId: params.observationPeriodId,
        },
        select: {
          id: true,
          plannedValue: true,
          plannedValueType: true,
          varianceAbsolute: true,
          varianceDirection: true,
          comparisonValid: true,
          attributionLevel: true,
        },
        orderBy: { createdAt: "desc" }, // most recent if multiple
      });

      // Layer 4: interpretations — alerts
      // B10 correction: only alerts for THIS indicator + strategy version
      const alerts = await tx.alert.findMany({
        where: {
          tenantId,
          indicatorDefinitionId: indicator.id,
          strategyVersionId: params.strategyVersionId,
        },
        select: {
          id: true,
          title: true,
          severity: true,
          lifecycleStage: true,
          executionStatus: true,
          isAutoGenerated: true,
        },
        orderBy: { createdAt: "desc" },
      });

      // Linked evidence (B11 correction: direct + related)
      const linkedEvidence = {
        supporting: [] as EvidenceSummary[],
        contradictory: [] as EvidenceSummary[],
        disputed: [] as EvidenceSummary[],
        refuted: [] as EvidenceSummary[],
      };

      if (currentObs?.evidenceId) {
        // Direct evidence
        const directEvidence = await tx.evidence.findFirst({
          where: { id: currentObs.evidenceId, tenantId },
          select: {
            id: true,
            claim: true,
            type: true,
            verificationStatus: true,
            sourceId: true,
            observedAt: true,
          },
        });
        if (directEvidence) {
          const summary: EvidenceSummary = {
            id: directEvidence.id,
            claim: directEvidence.claim,
            type: directEvidence.type,
            verificationStatus: directEvidence.verificationStatus,
            sourceId: directEvidence.sourceId,
            observedAt: directEvidence.observedAt?.toISOString() ?? null,
            relation: "direct",
          };
          categorizeEvidence(summary, linkedEvidence);
        }

        // Related evidence (via Evidence.relatedEvidenceId — relatedBy direction)
        // B11 correction: evidence that points TO the direct evidence
        const relatedEvidence = await tx.evidence.findMany({
          where: {
            tenantId,
            relatedEvidenceId: currentObs.evidenceId,
          },
          select: {
            id: true,
            claim: true,
            type: true,
            verificationStatus: true,
            sourceId: true,
            observedAt: true,
          },
        });
        for (const rel of relatedEvidence) {
          const summary: EvidenceSummary = {
            id: rel.id,
            claim: rel.claim,
            type: rel.type,
            verificationStatus: rel.verificationStatus,
            sourceId: rel.sourceId,
            observedAt: rel.observedAt?.toISOString() ?? null,
            relation: "related",
          };
          categorizeEvidence(summary, linkedEvidence);
        }
      }

      // Source provenance
      let sourceProvenance: IndicatorSnapshot["sourceProvenance"] = {
        sourceId: null,
        sourceCode: null,
        sourceDisplayName: null,
        independenceGroup: null,
        reviewStatus: null,
        submittedByTenantId: null,
        provenanceWarnings: [],
      };
      if (currentObs?.sourceId) {
        const source = await tx.source.findUnique({
          where: { id: currentObs.sourceId },
          select: {
            id: true,
            code: true,
            displayName: true,
            independenceGroup: true,
            reviewStatus: true,
            submittedByTenantId: true,
          },
        });
        if (source) {
          sourceProvenance = {
            sourceId: source.id,
            sourceCode: source.code,
            sourceDisplayName: source.displayName,
            independenceGroup: source.independenceGroup,
            reviewStatus: source.reviewStatus,
            submittedByTenantId: source.submittedByTenantId,
            provenanceWarnings: [], // populated below from observation qualityNotes
          };
        }
      }

      // Extract provenanceWarnings from current observation's qualityNotes
      if (currentObs) {
        // We need to fetch qualityNotes — wasn't in the select above
        const fullObs = await tx.observation.findUnique({
          where: { id: currentObs.id },
          select: { qualityNotes: true },
        });
        const qn = fullObs?.qualityNotes as unknown as Record<string, unknown> | null;
        if (qn && Array.isArray(qn.provenanceWarnings)) {
          sourceProvenance.provenanceWarnings = qn.provenanceWarnings as string[];
        }
      }

      // Layer 3: uncertainties
      const unknowns: string[] = [];
      if (!currentObs) unknowns.push("no current national-level observation");
      if (currentObs && currentObs.observedValue === null)
        unknowns.push("observedValue is null (unknown measurement)");
      if (!varianceRecord) unknowns.push("no variance record computed");
      if (varianceRecord && !varianceRecord.comparisonValid)
        unknowns.push("variance comparison not valid (no period-comparable target)");
      if (varianceRecord && varianceRecord.varianceDirection === "unknown")
        unknowns.push("variance direction unknown");

      // Per-indicator aggregate independence assessment
      const aggregateAnalysis = await analyzeAggregateIndependence(
        session,
        {
          indicatorId: indicator.id,
          observationPeriodId: params.observationPeriodId,
        }
      );

      if (aggregateAnalysis?.limitationReason) {
        allLimitations.add(aggregateAnalysis.limitationReason);
      }

      aggregateIndependenceByIndicator.push({
        indicatorId: indicator.id,
        indicatorCode: indicator.code,
        analysis: aggregateAnalysis,
      });

      const indicatorSnapshot: IndicatorSnapshot = {
        indicator: {
          id: indicator.id,
          code: indicator.code,
          displayName: indicator.displayName,
          unit: indicator.unit,
          preferredDirection: indicator.preferredDirection,
        },
        observedFacts: {
          currentObservation: currentObs
            ? {
                id: currentObs.id,
                observedValue:
                  currentObs.observedValue !== null
                    ? Number(currentObs.observedValue)
                    : null,
                observedAt: currentObs.observedAt?.toISOString() ?? null,
                originType: currentObs.originType,
                verificationStatus: currentObs.verificationStatus,
                isSynthetic: currentObs.isSynthetic,
                geoLevel: currentObs.geoLevel,
                geoRefId: currentObs.geoRefId,
              }
            : null,
          observationHistoryCount: allObsHistory.length,
          correctionChain: allObsHistory.map((o) => ({
            id: o.id,
            observedValue: o.observedValue !== null ? Number(o.observedValue) : null,
            correctionReason: o.correctionReason,
            correctedAt: o.correctedAt?.toISOString() ?? null,
            isCurrent: o.isCurrent,
          })),
        },
        calculatedComparisons: {
          varianceRecord: varianceRecord
            ? {
                id: varianceRecord.id,
                plannedValue:
                  varianceRecord.plannedValue !== null
                    ? Number(varianceRecord.plannedValue)
                    : null,
                plannedValueType: varianceRecord.plannedValueType,
                varianceAbsolute:
                  varianceRecord.varianceAbsolute !== null
                    ? Number(varianceRecord.varianceAbsolute)
                    : null,
                varianceDirection: varianceRecord.varianceDirection,
                comparisonValid: varianceRecord.comparisonValid,
                attributionLevel: varianceRecord.attributionLevel, // always "descriptive"
              }
            : null,
        },
        uncertainties: {
          unknowns,
          observabilityMode: aggregateAnalysis?.observabilityMode ?? "LOW",
          limitationReason: aggregateAnalysis?.limitationReason ?? null,
          independenceAssessment: {
            totalSources: aggregateAnalysis?.sourceDiversity.totalSources ?? 0,
            independentSourceCount:
              aggregateAnalysis?.sourceDiversity.independentSourceCount ?? 0,
            verifiedEvidenceCount:
              aggregateAnalysis?.evidenceStrength.verifiedEvidenceCount ?? 0,
            nationalClaimSupportLevel:
              aggregateAnalysis?.nationalClaimSupport.level ?? "none",
            geographicCoverageNotEqualsIndependence: true,
          },
        },
        interpretations: {
          alerts: alerts.map((a) => ({
            id: a.id,
            title: a.title,
            severity: a.severity,
            lifecycleStage: a.lifecycleStage,
            executionStatus: a.executionStatus,
            isAutoGenerated: a.isAutoGenerated,
          })),
        },
        linkedEvidence,
        sourceProvenance,
      };

      indicatorSnapshots.push(indicatorSnapshot);
    }

    // Audit
    await writeAuditTx(tx, {
      tenantId,
      actor: userId,
      action: "observatory.snapshot.generated",
      details: {
        strategyVersionId: params.strategyVersionId,
        observationPeriodId: params.observationPeriodId,
        indicatorCount: indicators.length,
      },
      status: "ok",
    });

    return {
      strategyVersion: {
        id: sv.id,
        status: sv.status,
        versionNumber: sv.versionNumber,
      },
      observationPeriod: {
        id: period.id,
        periodType: period.periodType,
        periodValue: period.periodValue,
      },
      indicators: indicatorSnapshots,
      aggregateIndependenceByIndicator,
      generatedAt: new Date().toISOString(),
      honesty: {
        simulatedData: anySimulated,
        limitations: Array.from(allLimitations),
        noCausalClaims: true,
      },
    };
  });
}

// Helper: categorize evidence into supporting/contradictory/disputed/refuted
function categorizeEvidence(
  summary: EvidenceSummary,
  linkedEvidence: {
    supporting: EvidenceSummary[];
    contradictory: EvidenceSummary[];
    disputed: EvidenceSummary[];
    refuted: EvidenceSummary[];
  }
): void {
  // A13: preserve all evidence — never delete/suppress
  // Categorize by verificationStatus first, then by type
  if (summary.verificationStatus === "refuted") {
    linkedEvidence.refuted.push(summary);
  } else if (summary.verificationStatus === "disputed") {
    linkedEvidence.disputed.push(summary);
  } else if (summary.type === "counter") {
    linkedEvidence.contradictory.push(summary);
  } else {
    // supporting or neutral with non-refuted/non-disputed status
    linkedEvidence.supporting.push(summary);
  }
}
