/**
 * R3 + E5: Evaluate thresholds for a VarianceRecord and raise an Alert if matched.
 *
 * Algorithm (deterministic, no eval):
 *   1. Load VarianceRecord + IndicatorDefinition
 *   2. If indicator.alertThresholds = [] → return null (R3: no auto-alert)
 *   3. Build VarianceContext
 *   4. Evaluate rules via evaluateThresholds() (pure function)
 *   5. If matches:
 *        - Create Alert (lifecycleStage = "detected", isAutoGenerated = true)
 *        - Auto-transition to "notified" in same transaction
 *        - writeAuditTx
 *        - Return Alert
 *   6. If not matches: return null
 */
export async function evaluateAndRaise(
  session: Session | null,
  varianceRecordId: string
): Promise<Alert | null> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:read");

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId, userId }) => {
      // 1. Load VarianceRecord + Indicator
      const varianceRecord = await tx.varianceRecord.findFirst({
        where: { id: varianceRecordId, tenantId },
      });
      if (!varianceRecord) {
        throw new NotFoundError(
          `VarianceRecord ${varianceRecordId} not found in tenant ${tenantId}`
        );
      }

      const indicator = await tx.indicatorDefinition.findFirst({
        where: { id: varianceRecord.indicatorDefinitionId, tenantId },
      });
      if (!indicator) {
        throw new NotFoundError(
          `Indicator ${varianceRecord.indicatorDefinitionId} not found`
        );
      }

      // 2. R3: empty alertThresholds → no auto-alert
      const thresholds = (indicator.alertThresholds ?? []) as unknown as Array<{
        metric: "varianceAbsolute" | "variancePercentage" | "varianceDirection";
        operator: "gt" | "gte" | "lt" | "lte" | "eq";
        value: number | "better" | "worse" | "neutral" | "unknown";
        logicalOp?: "and" | "or";
        severity: "info" | "watch" | "warning" | "critical";
        rationale: string;
        sourceRef: string;
      }>;

      if (thresholds.length === 0) {
        // R3: no thresholds → no alert
        return null;
      }

      // 3. Build VarianceContext
      const varianceAbsolute =
        varianceRecord.varianceAbsolute !== null
          ? Number(varianceRecord.varianceAbsolute)
          : null;
      const plannedValue =
        varianceRecord.plannedValue !== null
          ? Number(varianceRecord.plannedValue)
          : null;

      const ctx: VarianceContext = {
        varianceAbsolute,
        variancePercentage: computeVariancePercentage(varianceAbsolute, plannedValue),
        varianceDirection: varianceRecord.varianceDirection as VarianceContext["varianceDirection"],
      };

      // 4. Evaluate
      const result = evaluateThresholds(thresholds, ctx);

      // 5. If not matched, return null
      if (!result.matches || result.severity === null) {
        return null;
      }

      // 5. Create Alert (lifecycleStage = "detected")
      const alert = await tx.alert.create({
        data: {
          tenantId,
          strategyVersionId: varianceRecord.strategyVersionId,
          indicatorDefinitionId: indicator.id,
          varianceRecordId: varianceRecord.id,
          title: `Variance alert: ${indicator.displayName}`,
          description: `Auto-detected variance for indicator ${indicator.code} (direction: ${ctx.varianceDirection}, absolute: ${varianceAbsolute ?? "unknown"})`,
          severity: result.severity,
          lifecycleStage: "detected",
          executionStatus: "not_applicable",
          requiresHumanAction: true,
          createdBy: "system",
          isAutoGenerated: true,
          metadata: {
            varianceAbsolute,
            varianceDirection: ctx.varianceDirection,
            ruleCount: thresholds.length,
          },
        },
      });

      // 5. Auto-transition to "notified" in same transaction
      const updatedAlert = await tx.alert.update({
        where: { id: alert.id },
        data: { lifecycleStage: "notified" },
      });

      // 5. Atomic audit log
      await writeAuditTx(tx, {
        tenantId,
        actor: userId,
        action: "observatory.alert.raised",
        details: {
          alertId: alert.id,
          varianceRecordId,
          indicatorId: indicator.id,
          severity: result.severity,
          isAutoGenerated: true,
        },
        status: "ok",
      });

      return updatedAlert;
    }
  );
}

/**
 * Mark an alert as reviewed (lifecycleStage → "reviewed").
 * Valid from "detected" or "notified".
 */
export async function markReviewed(
  session: Session | null,
  alertId: string,
  notes: string
): Promise<Alert> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:review");

  if (!notes || notes.trim().length === 0) {
    throw new Error("Review notes are required");
  }

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId, userId }) => {
      const existing = await tx.alert.findFirst({
        where: { id: alertId, tenantId },
      });
      if (!existing) {
        throw new NotFoundError(`Alert ${alertId} not found`);
      }

      // Valid transitions: from "detected" or "notified"
      if (
        existing.lifecycleStage !== "detected" &&
        existing.lifecycleStage !== "notified"
      ) {
        throw new Error(
          `Cannot mark reviewed from lifecycleStage "${existing.lifecycleStage}"`
        );
      }

      const updated = await tx.alert.update({
        where: { id: alertId },
        data: {
          lifecycleStage: "reviewed",
          reviewedBy: userId,
          reviewedAt: new Date(),
          reviewNotes: notes,
        },
      });

      await writeAuditTx(tx, {
        tenantId,
        actor: userId,
        action: "observatory.alert.reviewed",
        details: { alertId, notes },
        status: "ok",
      });

      return updated;
    }
  );
}

/**
 * R5: Document a human decision on this alert.
 *
 * IMPORTANT: This documents WHAT the human decided, NOT that the decision
 * was executed. Execution verification is a separate block (see
 * verifyExecution).
 *
 * Valid from "reviewed" only.
 */
export async function documentDecision(
  session: Session | null,
  alertId: string,
  decisionDescription: string
): Promise<Alert> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:act");

  if (!decisionDescription || decisionDescription.trim().length === 0) {
    throw new Error("Decision description is required");
  }

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId, userId }) => {
      const existing = await tx.alert.findFirst({
        where: { id: alertId, tenantId },
      });
      if (!existing) {
        throw new NotFoundError(`Alert ${alertId} not found`);
      }

      if (existing.lifecycleStage !== "reviewed") {
        throw new Error(
          `Cannot document decision from lifecycleStage "${existing.lifecycleStage}" (must be "reviewed")`
        );
      }

      const updated = await tx.alert.update({
        where: { id: alertId },
        data: {
          lifecycleStage: "decision_documented",
          decisionDescription,
          decidedById: userId,
          decidedAt: new Date(),
        },
      });

      // R5: executionStatus is NOT changed by documentDecision.
      // It stays at whatever it was (typically "not_applicable").

      await writeAuditTx(tx, {
        tenantId,
        actor: userId,
        action: "observatory.alert.decision_documented",
        details: { alertId, decisionDescription },
        status: "ok",
      });

      return updated;
    }
  );
}

/**
 * R5 + F6: Update the execution status of an alert (separate from lifecycle).
 *
 * Valid from any lifecycleStage.
 *
 * If executionStatus = "verified":
 *   - verifiedAction MUST be provided (F6) — describes the SPECIFIC action verified
 *     (e.g., "receipt of memo #X by Ministry of Finance"), NOT a policy outcome
 *     (e.g., "inflation reduced")
 *   - evidenceSource MUST be provided (F6) — evidence for that specific action
 *
 * Does NOT change lifecycleStage.
 */
export async function updateExecutionStatus(
  session: Session | null,
  alertId: string,
  input: UpdateExecutionStatusInput
): Promise<Alert> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:act");

  const parsed = UpdateExecutionStatusInputSchema.parse(input);

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId, userId }) => {
      const existing = await tx.alert.findFirst({
        where: { id: alertId, tenantId },
      });
      if (!existing) {
        throw new NotFoundError(`Alert ${alertId} not found`);
      }

      const updateData: Record<string, unknown> = {
        executionStatus: parsed.executionStatus,
      };

      if (parsed.executionStatus === "verified") {
        updateData.executionVerifiedAction = parsed.verifiedAction;
        updateData.executionVerificationSource = parsed.evidenceSource;
        updateData.executionVerifiedById = userId;
        updateData.executionVerifiedAt = new Date();
        if (parsed.notes) {
          updateData.executionNotes = parsed.notes;
        }
      } else if (parsed.executionStatus === "disputed") {
        if (parsed.notes) {
          updateData.executionNotes = parsed.notes;
        }
      } else if (parsed.executionStatus === "pending") {
        // No additional fields
      }

      // R5: lifecycleStage is NOT changed.
      const updated = await tx.alert.update({
        where: { id: alertId },
        data: updateData,
      });

      await writeAuditTx(tx, {
        tenantId,
        actor: userId,
        action: "observatory.alert.execution_status_updated",
        details: {
          alertId,
          executionStatus: parsed.executionStatus,
          verifiedAction: parsed.verifiedAction ?? null,
        },
        status: "ok",
      });

      return updated;
    }
  );
}

/**
 * F6: Verify that a SPECIFIC DOCUMENTED ACTION was executed.
 *
 * SEMANTIC RULE (F6 — documented in code comment for clarity):
 *   "Verification confirms a SPECIFIC DOCUMENTED ACTION (e.g., 'memo received
 *    by ministry'), not a policy outcome (e.g., 'inflation reduced'). A receipt
 *    for a memo proves receipt, not policy execution. The verifiedAction field
 *    MUST describe the concrete action being verified, and evidenceSource MUST
 *    be evidence for that specific action."
 *
 * This is a convenience wrapper around updateExecutionStatus({executionStatus: "verified"}).
 *
 * Does NOT change lifecycleStage.
 */
export async function verifyExecution(
  session: Session | null,
  alertId: string,
  input: VerifyExecutionInput
): Promise<Alert> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:act");

  // F6: verifyExecution input requires verifiedAction + evidenceSource (Zod enforces)
  const parsed = VerifyExecutionInputSchema.parse(input);

  return updateExecutionStatus(session, alertId, {
    executionStatus: "verified",
    verifiedAction: parsed.verifiedAction,
    evidenceSource: parsed.evidenceSource,
    notes: parsed.notes,
  });
}

/**
 * Close an alert (lifecycleStage → "closed").
 * Valid from "reviewed" or later stages.
 *
 * R5: Does NOT require executionStatus = "verified".
 */
export async function closeAlert(
  session: Session | null,
  alertId: string,
  reason: string
): Promise<Alert> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:act");

  if (!reason || reason.trim().length === 0) {
    throw new Error("Closure reason is required");
  }

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId, userId }) => {
      const existing = await tx.alert.findFirst({
        where: { id: alertId, tenantId },
      });
      if (!existing) {
        throw new NotFoundError(`Alert ${alertId} not found`);
      }

      // Valid transitions: from "reviewed" or any later stage
      const validStages = [
        "reviewed",
        "decision_documented",
        "closed", // idempotent
      ];
      if (!validStages.includes(existing.lifecycleStage)) {
        throw new Error(
          `Cannot close from lifecycleStage "${existing.lifecycleStage}"`
        );
      }

      const updated = await tx.alert.update({
        where: { id: alertId },
        data: {
          lifecycleStage: "closed",
          closedBy: userId,
          closedAt: new Date(),
          closureReason: reason,
        },
      });

      await writeAuditTx(tx, {
        tenantId,
        actor: userId,
        action: "observatory.alert.closed",
        details: { alertId, reason },
        status: "ok",
      });

      return updated;
    }
  );
}

// ============================================================
// READ helpers — listAlerts + getAlert
// ------------------------------------------------------------
// Adds the missing read-side API to alert-service so HTTP routes
// can expose the full T2 lifecycle without bypassing the service
// layer (no raw Prisma in route handlers).
//
// Both reuse withAuthenticatedTenant for RLS enforcement + audit
// context, and requirePermissionWithCurrentRole("observatory:alert:read")
// so every role with alert:read (analyst/reviewer/admin/observer)
// can list/get, but only reviewer/admin can mutate (existing services).
// ============================================================

export interface AlertListItem {
  id: string;
  tenantId: string;
  strategyVersionId: string;
  indicatorDefinitionId: string | null;
  varianceRecordId: string | null;
  title: string;
  description: string;
  severity: string;
  lifecycleStage: string;
  executionStatus: string;
  isAutoGenerated: boolean;
  requiresHumanAction: boolean;
  createdAt: Date;
  updatedAt: Date;
  reviewedAt: Date | null;
  closedAt: Date | null;
}

/**
 * List alerts, optionally filtered by lifecycleStage / severity /
 * strategyVersionId / indicatorDefinitionId. RLS-enforced via
 * withAuthenticatedTenant — caller only ever sees alerts in their
 * current tenant.
 *
 * Sorted by createdAt DESC (most recent first) by default. Supports
 * an optional `limit` (capped at 200) for pagination.
 */
export async function listAlerts(
  session: Session | null,
  filter?: {
    lifecycleStage?: string;
    severity?: string;
    strategyVersionId?: string;
    indicatorDefinitionId?: string;
    limit?: number;
  }
): Promise<AlertListItem[]> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:read");

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId }) => {
      const where: Record<string, unknown> = { tenantId };
      if (filter?.lifecycleStage) where.lifecycleStage = filter.lifecycleStage;
      if (filter?.severity) where.severity = filter.severity;
      if (filter?.strategyVersionId)
        where.strategyVersionId = filter.strategyVersionId;
      if (filter?.indicatorDefinitionId)
        where.indicatorDefinitionId = filter.indicatorDefinitionId;

      // Cap limit at 200 to prevent unbounded scans
      const limit = Math.min(Math.max(filter?.limit ?? 50, 1), 200);

      const rows = await tx.alert.findMany({
        where,
        orderBy: { createdAt: "desc" },
        take: limit,
        select: {
          id: true,
          tenantId: true,
          strategyVersionId: true,
          indicatorDefinitionId: true,
          varianceRecordId: true,
          title: true,
          description: true,
          severity: true,
          lifecycleStage: true,
          executionStatus: true,
          isAutoGenerated: true,
          requiresHumanAction: true,
          createdAt: true,
          updatedAt: true,
          reviewedAt: true,
          closedAt: true,
        },
      });
      return rows;
    }
  );
}

/**
 * Get a single alert by id (within the caller's tenant — RLS enforced).
 *
 * Returns the full row (including decision/execution/closure fields) so
 * reviewers and admins can see the complete lifecycle state in one call.
 *
 * Throws NotFoundError if the alert does not exist in the caller's tenant
 * (so 404 from the route handler — does not leak existence across tenants).
 */
export async function getAlert(
  session: Session | null,
  alertId: string
): Promise<Alert> {
  await requirePermissionWithCurrentRole(session, "observatory:alert:read");

  return withAuthenticatedTenant(
    session,
    async ({ tx, tenantId }) => {
      const existing = await tx.alert.findFirst({
        where: { id: alertId, tenantId },
      });
      if (!existing) {
        throw new NotFoundError(`Alert ${alertId} not found`);
      }
      return existing;
    }
  );
}
