// tests/integration/g03-05-approval.integration.test.ts
// G03-05 — Integration tests for enhanced approval workflow.
import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { PrismaClient } from "@prisma/client";
import { hashPassword } from "@/lib/password";
import type { Session } from "next-auth";

const DATABASE_URL = process.env.DATABASE_URL ?? "";
const DIRECT_URL = process.env.DIRECT_URL ?? "";
const RUN_INTEGRATION = process.env.RUN_INTEGRATION_TESTS === "1";
const describeIntegration = RUN_INTEGRATION ? describe : describe.skip;

const FIXTURE_PREFIX = "g03-05-it-";

let adminClient: PrismaClient;
let tenantAId: string;
let analystUserId: string;
let reviewerUserId: string;
let adminUserId: string;
let strategyVersionId: string;
let createdAlertIds: string[] = [];
let createdProposalIds: string[] = [];
let createdAlternativeIds: string[] = [];

function makeSession(user: { id: string; tenantId: string; roleCode: string; membershipStatus: string }): Session {
  return { user: { id: user.id, tenantId: user.tenantId, roleCode: user.roleCode, membershipStatus: user.membershipStatus }, expires: new Date(Date.now() + 3600_000).toISOString() } as unknown as Session;
}

beforeAll(async () => {
  if (!RUN_INTEGRATION) return;
  adminClient = new PrismaClient({ datasources: { db: { url: DIRECT_URL } } });
  const tenantA = await adminClient.tenant.findUnique({ where: { code: "DML-MOP-TENANT" } });
  if (!tenantA) throw new Error("Tenants not seeded");
  tenantAId = tenantA.id;
  const adminUser = await adminClient.user.findUnique({ where: { email: "admin@demolandia.test" } });
  const analystUser = await adminClient.user.findUnique({ where: { email: "analyst@demolandia.test" } });
  if (!adminUser || !analystUser) throw new Error("Users not seeded");
  adminUserId = adminUser.id;
  analystUserId = analystUser.id;
  const reviewer = await adminClient.user.upsert({
    where: { email: "g03-05-reviewer@demolandia.test" },
    update: {},
    create: { email: "g03-05-reviewer@demolandia.test", name: "G03-05 Reviewer", passwordHash: await hashPassword("Test1234!"), status: "active" },
  });
  await adminClient.membership.upsert({
    where: { userId_tenantId: { userId: reviewer.id, tenantId: tenantAId } },
    update: { status: "active", roleCode: "reviewer" },
    create: { userId: reviewer.id, tenantId: tenantAId, roleCode: "reviewer", status: "active" },
  });
  reviewerUserId = reviewer.id;
  let sv = await adminClient.strategyVersion.findFirst({ where: { tenantId: tenantAId, status: "approved" } });
  if (!sv) {
    const strategy = await adminClient.strategy.create({ data: { tenantId: tenantAId, title: "G03-05 Strategy", createdBy: analystUserId } });
    sv = await adminClient.strategyVersion.create({ data: { strategyId: strategy.id, tenantId: tenantAId, versionNumber: 1, content: "{}", status: "approved", approvedBy: adminUserId, approvedAt: new Date(), metadata: { simulated: true }, createdBy: analystUserId } });
  }
  strategyVersionId = sv.id;
});

afterAll(async () => {
  if (!RUN_INTEGRATION) return;
  try {
    await adminClient.$executeRawUnsafe(`ALTER TABLE "reform_approvals" DISABLE TRIGGER prevent_delete_reform_approvals`);
    await adminClient.$executeRawUnsafe(`ALTER TABLE "reform_action_updates" DISABLE TRIGGER prevent_delete_reform_action_updates`);
    await adminClient.reformActionUpdate.deleteMany({ where: { id: { startsWith: FIXTURE_PREFIX } } });
    await adminClient.reformAction.deleteMany({ where: { id: { startsWith: FIXTURE_PREFIX } } });
    await adminClient.reformApproval.deleteMany({ where: { id: { startsWith: FIXTURE_PREFIX } } });
    await adminClient.reformAlternative.deleteMany({ where: { id: { in: createdAlternativeIds } } });
    await adminClient.reformProposal.deleteMany({ where: { id: { in: createdProposalIds } } });
    if (createdAlertIds.length > 0) await adminClient.alert.deleteMany({ where: { id: { in: createdAlertIds } } });
    await adminClient.$executeRawUnsafe(`ALTER TABLE "reform_approvals" ENABLE TRIGGER prevent_delete_reform_approvals`);
    await adminClient.$executeRawUnsafe(`ALTER TABLE "reform_action_updates" ENABLE TRIGGER prevent_delete_reform_action_updates`);
  } finally { await adminClient?.$disconnect(); }
});

async function createTestAlert(): Promise<string> {
  const alert = await adminClient.alert.create({ data: { id: `${FIXTURE_PREFIX}alert-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`, tenantId: tenantAId, strategyVersionId, title: "G03-05 Alert", description: "Test alert.", severity: "warning", lifecycleStage: "reviewed", executionStatus: "verified", executionVerifiedAction: "test", executionVerificationSource: "test", executionVerifiedById: reviewerUserId, executionVerifiedAt: new Date(), createdBy: "system", reviewedBy: reviewerUserId, reviewedAt: new Date(), isAutoGenerated: true, metadata: { simulated: true } } });
  createdAlertIds.push(alert.id);
  return alert.id;
}

async function setupProposalWithAlt(alertId?: string): Promise<{ proposalId: string; altId: string }> {
  const { createReformProposal } = await import("@/lib/reform/reform-proposal-service");
  const { addReformAlternative, selectAlternative } = await import("@/lib/reform/reform-alternative-service");
  const { submitForReview } = await import("@/lib/reform/reform-proposal-service");
  const analyst = makeSession({ id: analystUserId, tenantId: tenantAId, roleCode: "analyst", membershipStatus: "active" });
  const reviewer = makeSession({ id: reviewerUserId, tenantId: tenantAId, roleCode: "reviewer", membershipStatus: "active" });
  const aid = alertId ?? (await createTestAlert());
  const result = await createReformProposal(analyst, { originatingAlertId: aid, title: `${FIXTURE_PREFIX} Proposal`, problemStatement: "Test problem statement for G03-05 approval testing.", hypothesizedCauses: [], alternative: { title: `${FIXTURE_PREFIX} Alt`, description: "Test alternative for approval testing here.", costCurrency: "USD", riskLevel: "low", feasibilityScore: "high" } });
  createdProposalIds.push(result.proposalId);
  if (result.alternativeId) createdAlternativeIds.push(result.alternativeId);
  await submitForReview(analyst, result.proposalId);
  await selectAlternative(reviewer, { alternativeId: result.alternativeId! });
  return { proposalId: result.proposalId, altId: result.alternativeId! };
}

describeIntegration("G03-05 Enhanced Approval", () => {
  it("G05-1: approval creates evidence snapshot in metadata (not supportingEvidence)", async () => {
    const { approveReformProposalWithAuditSafe } = await import("@/lib/reform/reform-approval-service");
    const { getReformApproval } = await import("@/lib/reform/reform-approval-service");
    const reviewer = makeSession({ id: reviewerUserId, tenantId: tenantAId, roleCode: "reviewer", membershipStatus: "active" });
    const { proposalId, altId } = await setupProposalWithAlt();

    const result = await approveReformProposalWithAuditSafe(reviewer, { proposalId, rationale: "Approved for testing evidence snapshot functionality here." });
    expect(result.proposalStatus).toBe("approved");

    const approval = await getReformApproval(reviewer, proposalId);
    expect(approval).not.toBeNull();
    // supportingEvidence should be [] (no evidence linked in test)
    expect(Array.isArray(approval!.supportingEvidence)).toBe(true);
    expect((approval!.supportingEvidence as unknown[]).length).toBe(0);
    // metadata should have alternativeSnapshot
    const metadata = approval!.metadata as { alternativeSnapshot?: { title: string } };
    expect(metadata.alternativeSnapshot).toBeDefined();
    expect(metadata.alternativeSnapshot!.title).toContain("Alt");
  });

  it("G05-2: denied approval (analyst) → audit_log has 'denied' entry", async () => {
    const { approveReformProposalWithAuditSafe } = await import("@/lib/reform/reform-approval-service");
    const analyst = makeSession({ id: analystUserId, tenantId: tenantAId, roleCode: "analyst", membershipStatus: "active" });
    const { proposalId } = await setupProposalWithAlt();

    const beforeCount = await adminClient.auditLog.count({ where: { tenantId: tenantAId, status: "denied" } });
    await expect(
      approveReformProposalWithAuditSafe(analyst, { proposalId, rationale: "Should be denied because analyst cannot approve." })
    ).rejects.toThrow();
    const afterCount = await adminClient.auditLog.count({ where: { tenantId: tenantAId, status: "denied" } });
    expect(afterCount).toBeGreaterThan(beforeCount);
  });

  it("G05-3: conflict (wrong status) → NOT audited as denied", async () => {
    const { approveReformProposalWithAuditSafe } = await import("@/lib/reform/reform-approval-service");
    const reviewer = makeSession({ id: reviewerUserId, tenantId: tenantAId, roleCode: "reviewer", membershipStatus: "active" });
    // Create proposal but don't submit (status stays draft)
    const { createReformProposal } = await import("@/lib/reform/reform-proposal-service");
    const analyst = makeSession({ id: analystUserId, tenantId: tenantAId, roleCode: "analyst", membershipStatus: "active" });
    const alertId = await createTestAlert();
    const result = await createReformProposal(analyst, { originatingAlertId: alertId, title: `${FIXTURE_PREFIX} Draft Proposal`, problemStatement: "Test problem for denial classification testing.", hypothesizedCauses: [] });
    createdProposalIds.push(result.proposalId);

    const beforeDenied = await adminClient.auditLog.count({ where: { tenantId: tenantAId, status: "denied" } });
    await expect(
      approveReformProposalWithAuditSafe(reviewer, { proposalId: result.proposalId, rationale: "Should fail with conflict (not denied)." })
    ).rejects.toThrow();
    const afterDenied = await adminClient.auditLog.count({ where: { tenantId: tenantAId, status: "denied" } });
    // ConflictError should NOT produce a denied audit entry
    expect(afterDenied).toBe(beforeDenied);
  });

  it("G05-4: supersession — approving new proposal for same alert supersedes old one", async () => {
    const { approveReformProposalWithAuditSafe } = await import("@/lib/reform/reform-approval-service");
    const reviewer = makeSession({ id: reviewerUserId, tenantId: tenantAId, roleCode: "reviewer", membershipStatus: "active" });
    const alertId = await createTestAlert();

    // First proposal + approval
    const { proposalId: oldProposalId } = await setupProposalWithAlt(alertId);
    await approveReformProposalWithAuditSafe(reviewer, { proposalId: oldProposalId, rationale: "First approval for supersession testing here." });

    // Verify old proposal is approved
    const oldProposal = await adminClient.reformProposal.findUnique({ where: { id: oldProposalId } });
    expect(oldProposal!.status).toBe("approved");

    // Second proposal for same alert
    const { proposalId: newProposalId } = await setupProposalWithAlt(alertId);
    await approveReformProposalWithAuditSafe(reviewer, { proposalId: newProposalId, rationale: "Second approval — should supersede the first one." });

    // Verify old proposal is now superseded
    const oldAfter = await adminClient.reformProposal.findUnique({ where: { id: oldProposalId } });
    expect(oldAfter!.status).toBe("superseded");
    expect(oldAfter!.supersededById).toBe(newProposalId);
    expect(oldAfter!.supersededAt).not.toBeNull();

    // New proposal is approved
    const newAfter = await adminClient.reformProposal.findUnique({ where: { id: newProposalId } });
    expect(newAfter!.status).toBe("approved");

    // Old approval record is still immutable (exists, unchanged)
    const oldApproval = await adminClient.reformApproval.findFirst({ where: { proposalId: oldProposalId, tenantId: tenantAId } });
    expect(oldApproval).not.toBeNull();
    // metadata snapshot still has old alternative title
    const oldMeta = oldApproval!.metadata as { alternativeSnapshot?: { title: string } };
    expect(oldMeta.alternativeSnapshot).toBeDefined();
  });

  it("G05-5: proposals without alert — no supersession (originatingAlertId is required, skip)", async () => {
    // originatingAlertId is required by CreateReformProposalInputSchema (z.string().min(1))
    // So proposals without alerts cannot be created via the current API.
    // This test is a no-op — the schema enforces alert linkage.
    // If a future mission makes originatingAlertId optional, this test should
    // verify: no advisory lock acquired, no supersession check, approval succeeds.
    expect(true).toBe(true);
  });

  it("G05-6: snapshot API returns proposal + alternatives + approval", async () => {
    const { approveReformProposalWithAuditSafe } = await import("@/lib/reform/reform-approval-service");
    const reviewer = makeSession({ id: reviewerUserId, tenantId: tenantAId, roleCode: "reviewer", membershipStatus: "active" });
    const { proposalId } = await setupProposalWithAlt();
    await approveReformProposalWithAuditSafe(reviewer, { proposalId, rationale: "Approved for snapshot API testing purposes." });

    const { withAuthenticatedTenant } = await import("@/lib/security/tenant-context");
    const snapshot = await withAuthenticatedTenant(reviewer, async ({ tx, tenantId }) => {
      const proposal = await tx.reformProposal.findFirst({ where: { id: proposalId, tenantId } });
      const alternatives = await tx.reformAlternative.findMany({ where: { proposalId, tenantId } });
      const approval = await tx.reformApproval.findFirst({ where: { proposalId, tenantId } });
      return { proposal, alternatives, approval };
    });

    expect(snapshot.proposal).not.toBeNull();
    expect(snapshot.alternatives.length).toBeGreaterThan(0);
    expect(snapshot.approval).not.toBeNull();
  });

  it("G05-7: approval immutability — UPDATE on reform_approvals blocked by trigger", async () => {
    const { approveReformProposalWithAuditSafe } = await import("@/lib/reform/reform-approval-service");
    const reviewer = makeSession({ id: reviewerUserId, tenantId: tenantAId, roleCode: "reviewer", membershipStatus: "active" });
    const { proposalId } = await setupProposalWithAlt();
    const result = await approveReformProposalWithAuditSafe(reviewer, { proposalId, rationale: "Approved for immutability testing here." });

    // Attempt to UPDATE the approval record (should fail via trigger)
    await expect(
      adminClient.$executeRawUnsafe(`UPDATE "reform_approvals" SET "rationale" = 'tampered' WHERE "id" = '${result.approvalId}'`)
    ).rejects.toThrow();
  });
});
