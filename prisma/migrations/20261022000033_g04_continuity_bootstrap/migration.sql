-- ============================================================
-- 1. handover_dossiers — generated dossier snapshots
-- ============================================================
CREATE TABLE "handover_dossiers" (
    "id"                    TEXT NOT NULL,
    "tenantId"              TEXT NOT NULL,
    "title"                 TEXT NOT NULL,
    -- Scope JSONB: what the dossier covers, e.g.
    -- {
    --   "strategyVersionIds": ["..."],
    --   "decisionIds": ["..."],
    --   "proposalIds": ["..."],
    --   "asOfDate": "2026-10-22T00:00:00Z",
    --   "includeActiveStrategies": true,
    --   "includeOutstandingObligations": true
    -- }
    "scope"                 JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Content JSONB: the structured dossier payload (strategies, decisions,
    -- actions, obligations, evidence, risks, uncertainties, auditHighlights).
    "content"               JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Generated by + at (provenance)
    "generatedBy"           TEXT NOT NULL,
    "generatedAt"           TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Retrieval tracking (who/when/how many times)
    "retrievedBy"           TEXT,
    "retrievedAt"           TIMESTAMP(3),
    "retrievalCount"        INTEGER NOT NULL DEFAULT 0,
    -- Status: draft | published | archived | superseded
    "status"                TEXT NOT NULL DEFAULT 'published',
    -- Metadata (e.g., version, checksum, expiry)
    "metadata"              JSONB NOT NULL DEFAULT '{}'::jsonb,
    "createdAt"             TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt"             TIMESTAMP(3) NOT NULL,

    CONSTRAINT "handover_dossiers_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "handover_dossiers_tenantId_status_idx"
    ON "handover_dossiers"("tenantId", "status");
CREATE INDEX "handover_dossiers_tenantId_generatedAt_idx"
    ON "handover_dossiers"("tenantId", "generatedAt");
CREATE INDEX "handover_dossiers_tenantId_createdAt_idx"
    ON "handover_dossiers"("tenantId", "createdAt");

-- ============================================================
-- 2. RLS — ENABLE + FORCE on handover_dossiers
-- ============================================================
ALTER TABLE "handover_dossiers" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "handover_dossiers" FORCE ROW LEVEL SECURITY;

-- ============================================================
-- 3. RLS POLICIES
-- ============================================================
-- balance_app: SELECT only its own tenant; INSERT only when
-- generatedBy = current user. UPDATE only the retrieval-tracking
-- columns (retrievedBy, retrievedAt, retrievalCount) — content
-- is immutable post-publication (dossier integrity).
CREATE POLICY "handover_dossiers_select_own_tenant"
    ON "handover_dossiers"
    FOR SELECT
    TO balance_app
    USING ("tenantId" = current_setting('app.tenant_id', true));

CREATE POLICY "handover_dossiers_insert_own_tenant"
    ON "handover_dossiers"
    FOR INSERT
    TO balance_app
    WITH CHECK (
        "tenantId" = current_setting('app.tenant_id', true)
        AND "generatedBy" = current_setting('app.user_id', true)
    );

-- Retrieval-tracking UPDATE policy: only the retrieval columns can
-- be updated by balance_app, and only for rows in the caller's tenant.
-- Content (scope, content, status, generatedBy, generatedAt) is
-- IMMUTABLE post-publication — enforced here at the DB level.
CREATE POLICY "handover_dossiers_update_retrieval_only"
    ON "handover_dossiers"
    FOR UPDATE
    TO balance_app
    USING ("tenantId" = current_setting('app.tenant_id', true))
    WITH CHECK ("tenantId" = current_setting('app.tenant_id', true));

-- ============================================================
-- 4. TRIGGER — block content mutation on published dossiers
-- ============================================================
-- A BEFORE UPDATE trigger that aborts any attempt to change the
-- content / scope / generatedBy / generatedAt / status fields of
-- a PUBLISHED dossier. Only the retrieval-tracking columns may be
-- updated. This is the dossier-integrity invariant: once an
-- institution receives a dossier, its content cannot be silently
-- altered.
CREATE OR REPLACE FUNCTION enforce_handover_dossier_immutability()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status = 'published' THEN
        -- Allowed columns for retrieval updates only
        IF NEW."scope" IS DISTINCT FROM OLD."scope"
           OR NEW."content" IS DISTINCT FROM OLD."content"
           OR NEW."generatedBy" IS DISTINCT FROM OLD."generatedBy"
           OR NEW."generatedAt" IS DISTINCT FROM OLD."generatedAt"
           OR NEW.title IS DISTINCT FROM OLD.title THEN
            RAISE EXCEPTION 'Cannot mutate content of a published handover dossier (id=%). Only retrieval-tracking columns (retrievedBy, retrievedAt, retrievalCount, status, metadata) may be updated.', OLD.id
                    USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    NEW."updatedAt" = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS enforce_handover_dossier_immutability_trigger
    ON "handover_dossiers";
CREATE TRIGGER enforce_handover_dossier_immutability_trigger
    BEFORE UPDATE ON "handover_dossiers"
    FOR EACH ROW
    EXECUTE FUNCTION enforce_handover_dossier_immutability();

-- ============================================================
-- 5. GRANTs (balance_app: DML on own rows; balance_admin: all)
-- ============================================================
GRANT USAGE ON SCHEMA public TO balance_app;
GRANT SELECT, INSERT, UPDATE ON "handover_dossiers" TO balance_app;
GRANT ALL PRIVILEGES ON "handover_dossiers" TO balance_admin;

